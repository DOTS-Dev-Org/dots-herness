public enum ConversationLifecycleState: String, Sendable {
    case archived
    case restored
    case deleted
}

public struct MemorySnapshot: Sendable, Equatable {
    public var text: String
    public var revision: Int

    public init(text: String, revision: Int) {
        self.text = text
        self.revision = revision
    }
}

/// Which store a note comes from. Links may point from `user` to `project`, never
/// the other way: a repository note must not name anything that lives on this Mac.
public enum MemoryLayer: String, Sendable, Equatable {
    case project
    case user
}

/// One parsed note in the Obsidian-style vault. Notes are generated by the host
/// from event-backed state or from the user layer; the UI browses them.
public struct MemoryNote: Sendable, Equatable, Identifiable {
    public var id: String
    public var kind: String
    public var title: String
    public var path: String
    public var body: String
    public var tags: [String]
    public var links: [String]
    public var backlinks: [String]
    public var revision: Int
    public var resolved: Bool
    public var layer: MemoryLayer

    public init(
        id: String,
        kind: String,
        title: String,
        path: String,
        body: String = "",
        tags: [String] = [],
        links: [String] = [],
        backlinks: [String] = [],
        revision: Int = 0,
        resolved: Bool = true,
        layer: MemoryLayer = .project
    ) {
        self.id = id
        self.kind = kind
        self.title = title
        self.path = path
        self.body = body
        self.tags = tags
        self.links = links
        self.backlinks = backlinks
        self.revision = revision
        self.resolved = resolved
        self.layer = layer
    }
}

public struct MemoryVaultEdge: Sendable, Equatable, Identifiable {
    public var from: String
    public var to: String
    /// How often the two fired together: a task's calls to a tool. 1 for a plain link.
    public var weight: Int
    public var id: String { "\(from)->\(to)" }
    public init(from: String, to: String, weight: Int = 1) { self.from = from; self.to = to; self.weight = weight }
}

public struct MemoryVault: Sendable, Equatable {
    public var notes: [MemoryNote]
    public var edges: [MemoryVaultEdge]
    public init(notes: [MemoryNote] = [], edges: [MemoryVaultEdge] = []) {
        self.notes = notes
        self.edges = edges
    }
}

public enum WorkspaceMemoryError: Error, LocalizedError, Sendable {
    case noWorkspace
    case invalidManifest
    case invalidTransfer
    case snapshotUnavailable
    case snapshotRestoreFailed(String)

    public var errorDescription: String? {
        switch self {
        case .noWorkspace: return AppCopy.text("workspaceMemory.noWorkspace")
        case .invalidManifest: return AppCopy.text("workspaceMemory.invalidManifest")
        case .invalidTransfer: return AppCopy.text("memory.transfer.invalidArchive")
        case .snapshotUnavailable: return AppCopy.text("conversation.historyUnavailable")
        case .snapshotRestoreFailed(let path): return AppCopy.format("conversation.historyRestoreFailed", path)
        }
    }
}

@MainActor
public final class WorkspaceMemory {
    struct StoredIdentity: Codable {
        var personID: String
        var displayName: String
        var publicKey: String
        var deviceID: String
        var keyID: String
    }

    struct TaskRecord {
        var runID: String
        var promptSummary: String
        var promptHash: String
        var startedAt: String
        var provider: String
        var model: String
        var changedFiles: [[String: Any]] = []
        var tools: [String] = []
    }

    struct ActivityCompactionCursor {
        var path: String
        var deviceNumber: UInt64
        var fileNumber: UInt64
        var offset: UInt64
        var liveRunIDs: Set<String>
    }

    let paths: SupportPaths
    let fileManager: FileManager
    let snapshotStore: WorkspaceSnapshotStore
    /// What is known about the user across every project; see `UserProfile`.
    public let profile: UserProfile
    /// Turns already known to have a complete snapshot. The chat asks for every message
    /// on every redraw (each check reads and decodes a manifest from disk), and a
    /// complete snapshot cannot turn incomplete again except through the calls below,
    /// which clear this. Only positive answers are kept: an unfinished turn may complete.
    var completeSnapshotTurns = Set<String>()
    var workspaceURL: URL?
    var identity: StoredIdentity?
    var manifest: [String: Any]?
    var state: [String: Any] = [:]
    var events: [[String: Any]] = []
    var tasks: [String: TaskRecord] = [:]
    /// The append-only activity log is compacted by reading only bytes past this cursor.
    /// A replaced log or a run that is no longer live invalidates it.
    var activityCompactionCursor: ActivityCompactionCursor?
    var mapText = ""
    var mapRefreshInFlight = Set<String>()
    /// The repository's file names, kept until git's index moves; see `relevantFiles`.
    var fileIndex: (workspace: URL, stamp: Date, index: FileIndex, changes: [String: String])?
    /// What each source file declares, by path, kept while the file's date stands; read
    /// off the main actor by `symbolScan`, so the first request may go without it.
    var symbolCache: [String: FileIndex.Symbols] = [:]
    var symbolScan: Task<Void, Never>?
    /// The git index date a background `fileIndex` rebuild is running for.
    var fileIndexRebuildStamp: Date?
    /// Current local Tree-sitter graph and refresh jobs, kept separate from user preferences.
    var codeGraphCache: ProjectCodeGraph?
    var codeGraphLookupLoadAttempted = Set<String>()
    var codeGraphRefreshInFlight = Set<String>()
    var codeGraphCheckInFlight = false
    /// Technologies this project is built with, as last read from its manifests.
    public internal(set) var stack: [String] = []
    /// The person's switch. Off, nothing is created, recorded, learned or handed to a model;
    /// what was already kept stays on disk untouched. Undo snapshots are not memory and go on.
    public var enabled = true

    public init(paths: SupportPaths, fileManager: FileManager = .default) {
        self.paths = paths
        self.fileManager = fileManager
        self.snapshotStore = WorkspaceSnapshotStore(paths: paths, fileManager: fileManager)
        self.profile = UserProfile(root: paths.root)
        self.state = Self.emptyState()
    }

    public var memoryDirectory: URL? { workspaceURL?.appendingPathComponent(".mem", isDirectory: true) }
    public var projectID: String? { manifest?["projectId"] as? String }
    /// This Mac's private folder for the open project: tasks, chats, feedback,
    /// lessons and the person's project preferences. It sits outside the repository
    /// and is keyed by the project id, so every clone of one project shares it.
    public var userMemoryDirectory: URL? {
        // The id is read from the repository's own manifest, so it is untrusted. initializeWorkspace
        // only writes a UUID, and a UUID cannot name a path such as "../".
        guard enabled, let id = projectID, UUID(uuidString: id) != nil else { return nil }
        return paths.root.appendingPathComponent("user-memory", isDirectory: true).appendingPathComponent(id, isDirectory: true)
    }
    public var revision: Int { state["revision"] as? Int ?? 0 }
    public var memoryReady: Bool { manifest != nil }

    public func setWorkspace(_ url: URL?) {
        workspaceURL = url?.standardizedFileURL
        identity = nil
        manifest = nil
        state = Self.emptyState()
        events = []
        tasks = [:]
        mapText = ""
        codeGraphCache = nil
        codeGraphLookupLoadAttempted.removeAll()
        codeGraphRefreshInFlight.removeAll()
        guard let root = memoryDirectory,
              fileManager.fileExists(atPath: root.path) else { return }
        loadExisting()
        scheduleCodeGraphLookupLoadInBackground()
    }

    public func reload() {
        guard memoryDirectory != nil else { return }
        loadExisting()
    }

    var pendingSnapshots: [String: SnapshotJob] = [:]
    let pendingSnapshotsLock = NSLock()
}
